"""Per-turn illustrated-delivery advice plus a post-turn delivery guard.

The advice is the existing conservative ``pre_llm_call`` context. The guard is
deliberately narrow: when the advisor classified the turn as ``artifact``, a
final answer without a document link is not a completed delivery. Hermes's
``post_llm_call`` is observer-only, so enforcement happens in
``transform_llm_output``; ``post_llm_call`` records the verdict for the turn
ledger.
"""
from __future__ import annotations

import importlib.util
import json
import logging
import re
import threading
import time
from pathlib import Path

log = logging.getLogger(__name__)

# A delivered document is either a bridge file marker or a document URL, or a
# complete document attached through the chat's own media channel. Ordinary
# code/review URLs deliberately do not count. A bare image does NOT count: the
# reader asked for the document, and a screenshot of it is not the document.
_DOC_LINK = re.compile(
    r'(?m)^\s*##FILE:\s*\S+'
    r'|https?://[^\s]*(?:/docx/|/wiki/|/docs/|/drive/|/sheets/|/slides/)'
)
# `MEDIA:` is how Hermes ships a file to the chat. Only self-contained documents
# qualify here -- a PNG preview passes through the same channel and must not be
# mistaken for the deliverable.
_MEDIA_DOC = re.compile(r'(?m)^\s*MEDIA:\s*(\S+?\.(?:html|htm|pdf))\s*$', re.I)


def _delivered(text) -> bool:
    """Whether the reply actually handed over a document, not just a path."""
    text = text or ''
    if _DOC_LINK.search(text):
        return True
    for match in _MEDIA_DOC.finditer(text):
        try:
            if Path(match.group(1)).is_file():
                return True
        except OSError:
            continue
    return False
_GUARD_NOTE = (
    "\n\n---\n"
    "⚠️ 交付校验未通过：本轮要求图文文档，但最终回复里没有检测到文档链接或 `##FILE`。"
    "这不是完成态；请重试，或让运维检查渲染/投递链路。"
)
_PENDING_TTL_SECONDS = 600
# Gateway-injected messages (background-task completion, internal nudges) are not
# user requests. They quote long earlier context, so an intent classifier reads
# them as "the user asked for a progress report" and forces a document the user
# never asked for. Recognise the envelope and stay out of the way.
_INTERNAL_MARKERS = (
    '[INTERNAL NOTIFICATION',
    '[IMPORTANT: Background process',
    'generated by the Hermes gateway, not written by a human user',
)


def _is_internal(message):
    return isinstance(message, str) and any(m in message for m in _INTERNAL_MARKERS)



def _engine(ctx):
    try:
        from agentcore.document_intent import advise_delivery, delivery_context
        return advise_delivery, delivery_context
    except ModuleNotFoundError as error:
        if error.name not in ('agentcore', 'agentcore.document_intent'):
            raise
    # Installed Hermes runtimes can be isolated from the source checkout. The
    # administrator points at the single canonical engine; do not vendor a copy
    # or add task-controlled paths to the import search path.
    root = ctx.get_config('engine_root', '')
    if not isinstance(root, str) or not Path(root).is_absolute():
        raise ValueError('engine_root must identify the administrator-installed source checkout')
    source = Path(root).resolve(strict=True) / 'agentcore/document_intent.py'
    spec = importlib.util.spec_from_file_location('illustrated_delivery_engine', source)
    if spec is None or spec.loader is None:
        raise ImportError('document intent engine unavailable')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.advise_delivery, module.delivery_context


def _location_hint(ctx):
    root = ctx.get_config('engine_root', '')
    if not isinstance(root, str) or not Path(root).is_absolute():
        return ''
    try:
        root = Path(root).resolve(strict=True)
    except OSError:
        return ''
    renderer = root / 'tools/arch_doc.py'
    skill = root / 'skills/illustrated-doc-rendering/SKILL.md'
    if not renderer.is_file() or not skill.is_file():
        return ''
    return (' Canonical renderer file: ' + str(renderer) + '. Canonical skill file: ' + str(skill) +
            '. These are administrator-configured locations, not shell commands. '
            'Keep internal installation paths out of the delivered artifact.')


def _audit_path(ctx):
    configured = ctx.get_config('audit_path', '')
    if isinstance(configured, str) and configured:
        return Path(configured)
    manager = getattr(ctx, '_manager', None)
    home = getattr(manager, 'home_path', None)
    if home:
        return Path(home) / 'plugin-data' / 'illustrated-delivery' / 'delivery_guard.jsonl'
    return None


class _DeliveryGuard:
    """Advice, enforcement, and a small per-turn audit record."""

    def __init__(self, advise_delivery, delivery_context, location_hint, *,
                 include_delegated=False, audit_path=None):
        self._advise_delivery = advise_delivery
        self._delivery_context = delivery_context
        self._location_hint = location_hint
        self._include_delegated = include_delegated
        self._audit_path = audit_path
        self._pending = {}
        self._lock = threading.Lock()

    def _store(self, session_id, advice):
        now = time.time()
        with self._lock:
            stale = [key for key, entry in self._pending.items()
                     if now - entry['ts'] > _PENDING_TTL_SECONDS]
            for key in stale:
                self._pending.pop(key, None)
            self._pending[session_id] = {'advice': advice, 'ts': now, 'warned': False}

    def _entry(self, session_id):
        with self._lock:
            entry = self._pending.get(session_id)
            if entry and time.time() - entry['ts'] > _PENDING_TTL_SECONDS:
                self._pending.pop(session_id, None)
                return None
            return entry

    def _pop(self, session_id):
        with self._lock:
            return self._pending.pop(session_id, None)

    def before(self, *, user_message='', conversation_history=None,
               parent_session_id='', session_id='', **_kwargs):
        # Internal delegated calls should not recursively turn every tool task
        # into another document. The top-level caller owns the final deliverable.
        if parent_session_id and not self._include_delegated:
            return None
        # Internal gateway notices are not user turns: drop any stale advice for
        # this session and inject nothing, so the transform cannot demand a doc.
        if _is_internal(user_message):
            self._pop(session_id)
            return None
        if not isinstance(user_message, str):
            advice = self._advise_delivery('')
            self._store(session_id, advice)
            return {'context': self._delivery_context(advice) + self._location_hint}
        advice = self._advise_delivery(user_message, recent_messages=conversation_history)
        self._store(session_id, advice)
        return {'context': self._delivery_context(advice) + self._location_hint}

    def transform(self, *, response_text='', session_id='', **_kwargs):
        entry = self._entry(session_id)
        if not entry:
            return None
        advice = entry['advice']
        if advice.get('mode') != 'artifact':
            return None
        if _delivered(response_text):
            return None
        if entry['warned']:
            return None
        entry['warned'] = True
        return (response_text or '') + _GUARD_NOTE

    def after(self, *, session_id='', turn_id='', user_message='',
              assistant_response='', model='', platform='', **_kwargs):
        entry = self._pop(session_id)
        if not entry:
            return
        advice = entry['advice']
        record = {
            'ts': time.time(),
            'session_id': session_id,
            'turn_id': turn_id,
            'platform': platform,
            'model': model,
            'mode': advice.get('mode'),
            'kind': advice.get('kind'),
            'reason_code': advice.get('reason_code'),
            'artifact_expected': advice.get('mode') == 'artifact',
            'artifact_present': bool(_delivered(assistant_response or '')),
            'guard_warned': entry['warned'],
            'user_chars': len(user_message) if isinstance(user_message, str) else 0,
            'response_chars': len(assistant_response or ''),
        }
        self._write(record)

    def _write(self, record):
        if self._audit_path is None:
            return
        try:
            self._audit_path.parent.mkdir(parents=True, exist_ok=True)
            with self._lock, self._audit_path.open('a', encoding='utf-8') as handle:
                handle.write(json.dumps(record, ensure_ascii=False) + '\n')
        except OSError as exc:
            log.warning('delivery guard audit failed: %s', type(exc).__name__)


def register(ctx):
    if ctx.get_config('enabled', False) is not True:
        return
    advise_delivery, delivery_context = _engine(ctx)
    guard = _DeliveryGuard(
        advise_delivery,
        delivery_context,
        _location_hint(ctx),
        include_delegated=ctx.get_config('include_delegated', False) is True,
        audit_path=_audit_path(ctx),
    )
    ctx.register_hook('pre_llm_call', guard.before)
    # post_llm_call is observer-only in Hermes; the enforceable seam is the
    # output transform. Keep both so the audit sees the text the user saw.
    ctx.register_hook('transform_llm_output', guard.transform)
    ctx.register_hook('post_llm_call', guard.after)
